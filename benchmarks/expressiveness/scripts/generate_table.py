#!/usr/bin/env python3
"""Generate EXPRESSIVENESS_TABLE.md from catalog ratings and LOC counts."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

_EXPR = Path(__file__).resolve().parents[1]
if str(_EXPR) not in sys.path:
    sys.path.insert(0, str(_EXPR))

import yaml

from catalog import (
    FAILURE_SPECIFICITY,
    FAILURE_SPECIFICITY_GRADES,
    FRAMEWORK_LOC_ABBREVS,
    FRAMEWORK_RATINGS,
    SPECIMENS,
)

_SAMPLES_PATH = _EXPR / "failures_samples.yaml"

FRAMEWORKS = [
    "agent_spec_kit",
    "pytest_plain",
    "langsmith",
    "pydantic_evals",
    "promptfoo",
    "braintrust",
]


def _loc_map() -> dict[str, dict[str, int]]:
    script = _EXPR / "scripts" / "count_check_loc.py"
    proc = subprocess.run(
        [sys.executable, str(script)],
        capture_output=True,
        text=True,
        check=True,
        cwd=str(_EXPR),
    )
    result: dict[str, dict[str, int]] = {}
    current: str | None = None
    for line in proc.stdout.splitlines():
        if line.startswith("[") and line.endswith("]"):
            current = line[1:-1]
            result[current] = {}
        elif current and line.strip().startswith("C"):
            cid, _, n = line.strip().partition(":")
            result[current][cid] = int(n.strip())
    return result


def _load_failure_exemplars() -> dict[str, str]:
    if not _SAMPLES_PATH.is_file():
        return dict(FAILURE_SPECIFICITY_GRADES)
    data = yaml.safe_load(_SAMPLES_PATH.read_text(encoding="utf-8")) or {}
    ex = data.get("grade_exemplars") or {}
    return {g: str(ex.get(g, FAILURE_SPECIFICITY_GRADES[g])) for g in FAILURE_SPECIFICITY_GRADES}


def main() -> None:
    locs = _loc_map()
    exemplars = _load_failure_exemplars()
    out = _EXPR / "EXPRESSIVENESS_TABLE.md"
    lines = [
        "# Expressiveness / authoring-effort comparison",
        "",
        "Generated by `scripts/generate_table.py`. Re-run after changing implementations.",
        "",
        "| Check type | agent_spec_kit | Plain pytest | LangSmith | Pydantic Evals | Promptfoo | Braintrust | LOC (ask/py/ls/pe/pf/bt) | Failure specificity |",
        "| --- | --- | --- | --- | --- | --- | --- | ---: | --- |",
    ]
    for spec in SPECIMENS:
        cid = spec.check_id
        cells = [FRAMEWORK_RATINGS[fw].get(cid, "—") for fw in FRAMEWORKS]
        loc_parts = []
        for fw in FRAMEWORKS:
            loc_parts.append(str(locs.get(fw, {}).get(cid, "—")))
        loc_col = "/".join(loc_parts)
        fs = "/".join(FAILURE_SPECIFICITY[cid][fw] for fw in FRAMEWORKS)
        lines.append(
            f"| {spec.name} | {' | '.join(cells)} | {loc_col} | {fs} |"
        )
    totals_row = []
    for fw in FRAMEWORKS:
        total = sum(locs.get(fw, {}).values())
        totals_row.append(str(total) if total else "0")
    abbrevs = "/".join(abbr for _, abbr in FRAMEWORK_LOC_ABBREVS)
    lines.extend(
        [
            "",
            f"| **Total check LOC** | — | — | — | — | — | — | {'/'.join(totals_row)} | — |",
            "",
            "## How to read the columns",
            "",
            "### LOC (`" + abbrevs + "`)",
            "",
            "Non-comment lines between `CHECK_START` and `CHECK_END` in each framework port "
            "(full inlined check logic, not shared helpers). Order: "
            + ", ".join(f"**{abbr}** = {name}" for name, abbr in FRAMEWORK_LOC_ABBREVS)
            + ". **`—`** means no port for that check in that framework.",
            "",
            "### Failure specificity (`" + abbrevs + "`)",
            "",
            "Same order as LOC. Each letter is the **expected diagnostic quality** when that "
            "check fails on an intentional negative fixture (not pass/fail on golden traces). "
            "Lower letters mean harder debugging for operators.",
            "",
            "| Grade | Meaning |",
            "| --- | --- |",
        ]
    )
    for grade, meaning in FAILURE_SPECIFICITY_GRADES.items():
        ex = exemplars.get(grade, "")
        ex_cell = f"{meaning} Example: `{ex}`" if ex else meaning
        lines.append(f"| **{grade}** | {ex_cell} |")
    lines.extend(
        [
            "",
            "Grades are **manually** assigned from captured messages — see "
            "[`MANUAL_FAILURE_CLASSIFICATION.md`](MANUAL_FAILURE_CLASSIFICATION.md) "
            "(not keyword auto-scoring). Messages: [`failures_samples.yaml`](failures_samples.yaml).",
            "",
            "## Notes",
            "",
            "- Regenerate imperative ports: `uv run python scripts/materialize_inline_checks.py`",
            "- Re-count LOC: `uv run python scripts/count_check_loc.py`",
            "- Authoring clarity (LLM A–D, combined): [`READABILITY_TABLE.md`](READABILITY_TABLE.md)",
            "- Oracle reference: [`CANONICAL_SPEC.md`](CANONICAL_SPEC.md); **C01** uses a deterministic keyword rubric in every framework.",
            "- **agent_spec_kit** matchers are equivalent to imperative ports (`tests/test_ask_matcher_parity.py`); higher ask LOC is declarative DSL, not a different policy.",
        ]
    )
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
