#!/usr/bin/env python3
"""Generate READABILITY_TABLE.md from readability_records.json."""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

_EXPR = Path(__file__).resolve().parents[1]
if str(_EXPR) not in sys.path:
    sys.path.insert(0, str(_EXPR))

from catalog import FRAMEWORK_LOC_ABBREVS, SPECIMENS
from scripts.readability_quality_lib import AUTHORING_CLARITY_RUBRIC, RECORDS_PATH

GRADE_ORDINAL = {"A": 4, "B": 3, "C": 2, "D": 1}


def _abbr(fw: str) -> str:
    for name, abbr in FRAMEWORK_LOC_ABBREVS:
        if name == fw:
            return abbr
    return fw[:3]


def main() -> None:
    if not RECORDS_PATH.is_file():
        raise SystemExit(f"Missing {RECORDS_PATH}; run score_readability_quality.py first")

    records: dict[str, dict] = json.loads(RECORDS_PATH.read_text(encoding="utf-8"))
    fw_order = [fw for fw, _ in FRAMEWORK_LOC_ABBREVS]
    abbrs = "/".join(abbr for _, abbr in FRAMEWORK_LOC_ABBREVS)

    def grade_cell(check_id: str, fw: str) -> str:
        key = f"{check_id}|{fw}"
        la = records.get(key, {}).get("llm_assessment") or {}
        g = la.get("clarity_grade")
        return str(g) if g else "—"

    lines = [
        "# Authoring clarity (LLM-judged)",
        "",
        "Generated by `scripts/generate_readability_table.py`. "
        "Single combined grade per cell: **A best, D worst**. "
        "Covers test intent, scenario message/check flow, and how easy the code "
        "is to understand (properties, tools, objects). "
        "Distinct from failure-message specificity (A–E).",
        "",
        "## Rubric (A–D)",
        "",
        AUTHORING_CLARITY_RUBRIC.strip(),
        "",
        f"## Authoring clarity by check (`{abbrs}`)",
        "",
        "| Check type | " + " | ".join(_abbr(fw) for fw in fw_order) + " |",
        "| --- | " + " | ".join(["---"] * len(fw_order)) + " |",
    ]
    for spec in SPECIMENS:
        cid = spec.check_id
        cells = [grade_cell(cid, fw) for fw in fw_order]
        lines.append(f"| {spec.name} | {' | '.join(cells)} |")

    lines.extend(["", "## Per-framework grade counts", ""])
    for fw in fw_order:
        ctr: Counter[str] = Counter()
        for spec in SPECIMENS:
            g = grade_cell(spec.check_id, fw)
            if g in GRADE_ORDINAL:
                ctr[g] += 1
        mean = (
            sum(GRADE_ORDINAL[g] * ctr[g] for g in ctr) / sum(ctr.values())
            if ctr
            else 0
        )
        dist = ", ".join(f"{g}={ctr[g]}" for g in "ABCD" if ctr[g])
        lines.append(f"- **{_abbr(fw)}**: {dist} (mean ordinal {mean:.2f})")

    out = _EXPR / "READABILITY_TABLE.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
